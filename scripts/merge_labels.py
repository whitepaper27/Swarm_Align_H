"""Merge two independent labelers' outputs (T12 live labels, T14 flag review).

  uv run python scripts/merge_labels.py

Reads docs/labels/labeler_{a,b}_{live,flags}.jsonl and, if present, the owner's rulings in
docs/labels/adjudications.jsonl. Writes:
- docs/labels/agreement.md: per-field agreement and Cohen's kappa (generated);
- docs/labels/disagreements.md: every item the labelers disagree on, for the owner to rule on;
- docs/labels/live_labels_final.jsonl and flag_review_final.jsonl, **only** when every disagreement
  has a ruling. Agreed items are taken as labeled; disagreements take the owner's ruling.

Owner ruling format (one JSON object per line):
  {"kind": "live"|"flags", "episode_id": "...", "label": {<full label object>}, "by": "Sahil Soni"}
"""

from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

LAB = Path(__file__).resolve().parent.parent / "docs" / "labels"
KEYS = {"live": ("origin", "worker_refused", "publisher_adopted_claim"), "flags": ("verdict",)}


def _read(path: Path) -> dict[str, dict]:
    if not path.exists():
        raise SystemExit(f"missing {path}")
    rows = [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]
    return {r["episode_id"]: r for r in rows}


def kappa(a: list, b: list) -> float | None:
    n = len(a)
    if n == 0:
        return None
    po = sum(x == y for x, y in zip(a, b, strict=True)) / n
    ca, cb = collections.Counter(a), collections.Counter(b)
    pe = sum(ca[k] * cb[k] for k in set(ca) | set(cb)) / (n * n)
    return 1.0 if pe == 1 else (po - pe) / (1 - pe)


def main() -> int:
    rulings: dict[tuple[str, str], dict] = {}
    adj = LAB / "adjudications.jsonl"
    if adj.exists():
        for line in adj.read_text(encoding="utf-8").splitlines():
            if line.strip():
                r = json.loads(line)
                rulings[(r["kind"], r["episode_id"])] = r["label"]
    report = ["# Labeler agreement (generated by scripts/merge_labels.py)", ""]
    disagree = ["# Disagreements for owner adjudication (generated)", ""]
    pending = 0
    finals: dict[str, list[dict]] = {}
    for kind, keys in KEYS.items():
        a = _read(LAB / f"labeler_a_{kind}.jsonl")
        b = _read(LAB / f"labeler_b_{kind}.jsonl")
        if set(a) != set(b):
            raise SystemExit(f"{kind}: labelers covered different episodes: {set(a) ^ set(b)}")
        ids = sorted(a)
        report += [f"## {kind} ({len(ids)} items)", "", "| Field | Agreement | Cohen's kappa |"]
        report += ["|---|---|---|"]
        for k in keys:
            va, vb = [a[i][k] for i in ids], [b[i][k] for i in ids]
            agree = sum(x == y for x, y in zip(va, vb, strict=True))
            kap = kappa(va, vb)
            report.append(
                f"| {k} | {agree}/{len(ids)} | {'n/a' if kap is None else f'{kap:.2f}'} |"
            )
        report.append("")
        out = []
        for i in ids:
            if all(a[i][k] == b[i][k] for k in keys):
                out.append({**a[i], "source": "agreed"})
            elif (kind, i) in rulings:
                out.append({**rulings[(kind, i)], "episode_id": i, "source": "owner_ruling"})
            else:
                pending += 1
                disagree += [
                    f"## {kind} · {i}",
                    "",
                    f"- A: `{json.dumps({k: a[i][k] for k in keys})}`: {a[i].get('quote', '')!r}",
                    f"  note: {a[i].get('note', '')}",
                    f"- B: `{json.dumps({k: b[i][k] for k in keys})}`: {b[i].get('quote', '')!r}",
                    f"  note: {b[i].get('note', '')}",
                    "",
                ]
        finals[kind] = out
    (LAB / "agreement.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    if pending:
        (LAB / "disagreements.md").write_text("\n".join(disagree) + "\n", encoding="utf-8")
        print(f"{pending} disagreement(s) need an owner ruling: docs/labels/disagreements.md")
        return 1
    (LAB / "disagreements.md").write_text(disagree[0] + "\n\nNone outstanding.\n", "utf-8")
    for kind, name in (("live", "live_labels_final.jsonl"), ("flags", "flag_review_final.jsonl")):
        (LAB / name).write_text(
            "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in finals[kind]), "utf-8"
        )
    print("final labels written: live_labels_final.jsonl, flag_review_final.jsonl")
    return 0


if __name__ == "__main__":
    sys.exit(main())
